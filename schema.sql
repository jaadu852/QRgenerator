-- CloudKrafts QR Manager production schema (Supabase PostgreSQL)
CREATE TABLE IF NOT EXISTS vendors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  contact TEXT,
  secret TEXT NOT NULL,
  password_local TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS qr (
  id TEXT PRIMARY KEY,
  vendor_id BIGINT NOT NULL REFERENCES vendors(id),
  status TEXT NOT NULL DEFAULT 'unused',
  shop TEXT DEFAULT '',
  url TEXT DEFAULT '',
  pin TEXT DEFAULT '',
  batch_id TEXT DEFAULT '',
  downloaded_at TIMESTAMPTZ DEFAULT NULL,
  created TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  qr TEXT,
  action TEXT,
  at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_qr_batch ON qr(batch_id);
CREATE INDEX IF NOT EXISTS idx_qr_vendor ON qr(vendor_id);
